import { BossPhase, EnemyAttack, EnemyItem } from './types';

function gdQuote(value: string): string {
  const escaped = value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r/g, '').replace(/\n/g, '\\n');
  return `"${escaped}"`;
}

function attackRecord(attack: EnemyAttack) {
  return {
    id: attack.id,
    name: attack.name,
    type: attack.type,
    damage: attack.damage,
    parryable: attack.parryable,
    telegraph: attack.telegraphTime,
    cooldown: attack.cooldown,
    description: attack.description
  };
}

function phaseRecord(phase: BossPhase) {
  return {
    phase: phase.phaseNumber,
    name: phase.name,
    hp_threshold: phase.hpThresholdPercent,
    speed_mult: phase.speedMultiplier,
    description: phase.description,
    music: phase.musicTrack ?? '',
    new_attacks: phase.newAttacks.map(attackRecord)
  };
}

export function exportEnemyToTres(enemy: EnemyItem): string {
  const attacksData = JSON.stringify(enemy.attacks.map(attackRecord));
  const phasesData = JSON.stringify((enemy.phases || []).map(phaseRecord));
  const checklistData = JSON.stringify(enemy.checklist);
  const roomsData = JSON.stringify(enemy.spawnRoomIds);

  return `[gd_resource type="Resource" script_class="EnemyData" load_steps=2 format=3]

[ext_resource type="Script" path="res://scripts/resources/enemy_data.gd" id="1_enemy_script"]

[resource]
script = ExtResource("1_enemy_script")
id = ${gdQuote(enemy.id)}
code = ${gdQuote(enemy.code)}
name = ${gdQuote(enemy.name)}
type = ${gdQuote(enemy.type)}
sector_id = ${gdQuote(enemy.sectorId)}
max_hp = ${enemy.hp}
base_damage = ${enemy.damage}
move_speed = ${enemy.speed}.0
stagger_threshold = ${enemy.staggerThreshold}
parry_window = ${enemy.parryWindow}
godot_scene = ${gdQuote(enemy.godotScene)}
description = ${gdQuote(enemy.description)}
lore = ${gdQuote(enemy.lore)}
image_url = ${gdQuote(enemy.imageUrl ?? '')}
spawn_rooms = ${roomsData}
checklist = ${checklistData}
attacks = ${attacksData}
phases = ${phasesData}
`;
}

export function exportEnemyDatabaseGdscript(enemies: EnemyItem[]): string {
  const lines: string[] = [
    '# =====================================================================',
    '# AUTO-GENERATED BY CYBER-DUCK DEV HUB • BESTIARY COMBAT DESIGN DATABASE',
    '# Engine: Godot 4.3+ • Custom Resource & Static Lookup',
    '# Timestamp: ' + new Date().toISOString(),
    '# =====================================================================',
    'class_name EnemyDatabase',
    'extends RefCounted',
    '',
    'const ENEMIES: Dictionary = {'
  ];

  enemies.forEach(enemy => {
    lines.push(`\t${gdQuote(enemy.id)}: {`);
    lines.push(`\t\t"code": ${gdQuote(enemy.code)},`);
    lines.push(`\t\t"name": ${gdQuote(enemy.name)},`);
    lines.push(`\t\t"type": ${gdQuote(enemy.type)},`);
    lines.push(`\t\t"sector": ${gdQuote(enemy.sectorId)},`);
    lines.push(`\t\t"hp": ${enemy.hp},`);
    lines.push(`\t\t"damage": ${enemy.damage},`);
    lines.push(`\t\t"speed": ${enemy.speed},`);
    lines.push(`\t\t"stagger_threshold": ${enemy.staggerThreshold},`);
    lines.push(`\t\t"parry_window": ${enemy.parryWindow},`);
    lines.push(`\t\t"scene": ${gdQuote(enemy.godotScene)},`);
    lines.push(`\t\t"description": ${gdQuote(enemy.description)},`);
    lines.push(`\t\t"lore": ${gdQuote(enemy.lore)},`);
    lines.push(`\t\t"image_url": ${gdQuote(enemy.imageUrl ?? '')},`);
    lines.push(`\t\t"spawn_rooms": ${JSON.stringify(enemy.spawnRoomIds)},`);
    lines.push(`\t\t"checklist": ${JSON.stringify(enemy.checklist)},`);
    lines.push(`\t\t"attacks": ${JSON.stringify(enemy.attacks.map(attackRecord))},`);
    lines.push(`\t\t"phases": ${JSON.stringify((enemy.phases || []).map(phaseRecord))}`);
    lines.push('\t},');
  });

  lines.push('}');
  lines.push('');
  lines.push('static func get_enemy(id: String) -> Dictionary:');
  lines.push('\tif ENEMIES.has(id):');
  lines.push('\t\treturn ENEMIES[id]');
  lines.push('\tpush_error("Enemy not found in EnemyDatabase: " + id)');
  lines.push('\treturn {}');
  lines.push('');
  lines.push('static func get_bosses() -> Array:');
  lines.push('\tvar result = []');
  lines.push('\tfor key in ENEMIES:');
  lines.push('\t\tif ENEMIES[key]["type"] == "boss":');
  lines.push('\t\t\tresult.append(ENEMIES[key])');
  lines.push('\treturn result');

  return lines.join('\n');
}

export function exportBestiaryToJson(enemies: EnemyItem[]): string {
  const payload = {
    project: 'Cyber-Duck Metroidvania',
    version: '1.0.0',
    engine: 'Godot 4.3+',
    timestamp: new Date().toISOString(),
    totalEnemies: enemies.length,
    enemies
  };
  return JSON.stringify(payload, null, 2);
}
